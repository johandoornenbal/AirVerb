#!/usr/bin/env python3
"""Reproduce ClearCoat's SDK-free adapter without changing processing bodies."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
src = root / 'third_party/airwindows/ClearCoat'
h = (src / 'ClearCoat.h').read_text()
state = h.split('private:')[1].split('_canDo;')[1].rsplit('};',1)[0]
constants = h[h.index('const int kshortA'):h.index('const int kNumPrograms')].replace('const int ', 'inline static constexpr int ')
ctor = (src / 'ClearCoat.cpp').read_text().split('AudioEffectX(audioMaster, kNumPrograms, kNumParameters)\n{')[1].split('_canDo.insert')[0]
for channel, seed in [('L', '0x12345678u'), ('R', '0x87654321u')]:
    ctor = re.sub(rf'fpd{channel} = 1.0; while \(fpd{channel} < 16386\) fpd{channel} = rand\(\)\*UINT32_MAX;', f'fpd{channel} = {seed};', ctor)
header = '''#pragma once
// Airwindows ClearCoat (MIT). Generated by scripts/port-clearcoat.py.
#include <cstdint>
#include <cmath>
#include <algorithm>
class ClearCoatEngine {
public:
    ClearCoatEngine() { reset(44100.); }
    void reset(double sampleRate);
    void setParameter(int index, float value);
    void processReplacing(float**, float**, int);
    void processDoubleReplacing(double**, double**, int);
    double getSampleRate() const { return rate; }
private:
    double rate=44100.;
'''+constants+state+'\n};\n'
proc = (src / 'ClearCoatProc.cpp').read_text()
proc = proc[proc.index('void ClearCoat::processReplacing'):].replace('ClearCoat::', 'ClearCoatEngine::').replace('VstInt32','int')
setter = '''void ClearCoatEngine::setParameter(int index, float value) {
    if (!std::isfinite(value)) return;
    value=std::clamp(value,0.f,1.f);
    switch(index) {
'''+''.join(f'        case {i}: {c}=value; break;\n' for i,c in enumerate('AB'))+'''        default: break;
    }
}
'''
(root / 'Source/ClearCoatEngine.h').write_text(header)
(root / 'Source/ClearCoatEngine.cpp').write_text('// Airwindows ClearCoat (MIT). Generated by scripts/port-clearcoat.py.\n#include "ClearCoatEngine.h"\nvoid ClearCoatEngine::reset(double sampleRate) {\n    rate=sampleRate;\n'+ctor+'\n}\n'+setter+proc)
