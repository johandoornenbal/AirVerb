#!/usr/bin/env python3
"""Reproduce Srsly3's SDK-free adapter without changing processing bodies."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
src = root / 'third_party/airwindows/Srsly3'
h = (src / 'Srsly3.h').read_text()
state = h.split('private:')[1].split('_canDo;')[1].rsplit('};',1)[0]
constants = ''
ctor = (src / 'Srsly3.cpp').read_text().split('AudioEffectX(audioMaster, kNumPrograms, kNumParameters)\n{')[1].split('_canDo.insert')[0]
for channel, seed in [('L', '0x12345678u'), ('R', '0x87654321u')]:
    ctor = re.sub(rf'fpd{channel} = 1.0; while \(fpd{channel} < 16386\) fpd{channel} = rand\(\)\*UINT32_MAX;', f'fpd{channel} = {seed};', ctor)
header = '''#pragma once
// Airwindows Srsly3 (MIT). Generated by scripts/port-srsly3.py.
#include <cstdint>
#include <cmath>
#include <algorithm>
class Srsly3Engine {
public:
    Srsly3Engine() { reset(44100.); }
    void reset(double sampleRate);
    void setParameter(int index, float value);
    void processReplacing(float**, float**, int);
    void processDoubleReplacing(double**, double**, int);
    double getSampleRate() const { return rate; }
private:
    double rate=44100.;
'''+constants+state+'\n};\n'
proc = (src / 'Srsly3Proc.cpp').read_text()
proc = proc[proc.index('void Srsly3::processReplacing'):].replace('Srsly3::', 'Srsly3Engine::').replace('VstInt32','int')
setter = '''void Srsly3Engine::setParameter(int index, float value) {
    if (!std::isfinite(value)) return;
    value=std::clamp(value,0.f,1.f);
    switch(index) {
'''+''.join(f'        case {i}: {c}=value; break;\n' for i,c in enumerate('ABCDEF'))+'''        default: break;
    }
}
'''
(root / 'Source/Srsly3Engine.h').write_text(header)
(root / 'Source/Srsly3Engine.cpp').write_text('// Airwindows Srsly3 (MIT). Generated by scripts/port-srsly3.py.\n#include "Srsly3Engine.h"\nvoid Srsly3Engine::reset(double sampleRate) {\n    rate=sampleRate;\n'+ctor+'\n}\n'+setter+proc)
